"""Render the Mac test stack's LiteLLM files from the homelab values (one source of truth).

Writes mac/.generated/ (git-ignored):
  litellm-config.yaml   proxy_config of values/litellm-homelab.yaml, family aliases only
  bootstrap/            keys.json (family keys only), teams.json, bootstrap.py
                        from values/litellm-bootstrap.yaml, run once by the compose stack

The Mac has no local model, so `local` and every fallback to it are dropped: a spent
budget answers with an error there instead of falling back. On the homelab the
same aliases fall back to `local` (scripts/check-budget-fallback.py).

    uv run --no-project --with pyyaml==6.0.2 python mac/render.py
"""

import copy
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "mac" / ".generated"
FAMILY_PREFIX = "chat-"
FAMILY_ENVS = {"TEODOR_KEY", "TEODORA_KEY"}


def litellm_config() -> dict:
    proxy = yaml.safe_load((ROOT / "values" / "litellm-homelab.yaml").read_text())["proxy_config"]
    base = yaml.safe_load((ROOT / "values" / "litellm.yaml").read_text())["proxy_config"]
    models = [copy.deepcopy(m) for m in proxy["model_list"] if m["model_name"].startswith(FAMILY_PREFIX)]
    if not models:
        sys.exit(f"no {FAMILY_PREFIX}* aliases in values/litellm-homelab.yaml")
    names = {m["model_name"] for m in models}
    fallbacks = []
    for rule in proxy["router_settings"]["fallbacks"]:
        for alias, targets in rule.items():
            kept = [t for t in targets if t in names]
            if alias in names and kept:
                fallbacks.append({alias: kept})
    router = {**base.get("router_settings", {}), "fallbacks": fallbacks}
    return {
        "model_list": models,
        "router_settings": router,
        # No Phoenix / Prometheus on the Mac: callbacks off, the rest as in the cluster.
        "litellm_settings": {"drop_params": True},
        "general_settings": {"master_key": "os.environ/PROXY_MASTER_KEY"},
    }


def bootstrap_files() -> dict[str, str]:
    data = yaml.safe_load((ROOT / "values" / "litellm-bootstrap.yaml").read_text())["extraResources"][0]["data"]
    keys = [k for k in json.loads(data["keys.json"]) if k.get("secret_env") in FAMILY_ENVS]
    if len(keys) != len(FAMILY_ENVS):
        sys.exit("values/litellm-bootstrap.yaml keys.json is missing a family key")
    return {
        "keys.json": json.dumps(keys, indent=2) + "\n",
        "teams.json": "[]\n",
        "bootstrap.py": data["bootstrap.py"],
    }


def main() -> None:
    (OUT / "bootstrap").mkdir(parents=True, exist_ok=True)
    header = "# Generated by mac/render.py from values/litellm*.yaml - do not edit.\n"
    (OUT / "litellm-config.yaml").write_text(header + yaml.safe_dump(litellm_config(), sort_keys=False))
    for name, text in bootstrap_files().items():
        (OUT / "bootstrap" / name).write_text(text)
    print(f"rendered {OUT.relative_to(ROOT)}/litellm-config.yaml and bootstrap/")


if __name__ == "__main__":
    main()
